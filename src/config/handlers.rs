use anyhow::Result;
use std::collections::HashMap;

use super::types::{CategoryClaim, ConfigHandler, Definition, GenericDefinition, PropertyMap};
use crate::types::{CapabilityDefinition, ComponentDefinition, default_scope};

/// Handles `[component.*]` definitions.
pub struct ComponentConfigHandler;

impl ConfigHandler for ComponentConfigHandler {
    fn claimed_categories(&self) -> Vec<CategoryClaim> {
        vec![CategoryClaim::all("component")]
    }

    fn claimed_properties(&self) -> HashMap<&str, &[&str]> {
        HashMap::from([(
            "component",
            [
                "uri",
                "scope",
                "imports",
                "interceptors",
                "config",
                "labels",
            ]
            .as_slice(),
        )])
    }

    fn handle_definition(&mut self, definition: GenericDefinition) -> Result<Vec<Definition>> {
        let GenericDefinition {
            category,
            name,
            mut properties,
        } = definition;
        if category != "component" {
            return Err(anyhow::anyhow!(
                "ComponentConfigHandler received unexpected category '{category}'"
            ));
        }
        let ctx = |e: PropertyError| e.with_context("component", &name);
        let uri = take_required_string(&mut properties, "uri").map_err(ctx)?;
        let scope = take_optional_string(&mut properties, "scope")
            .map_err(ctx)?
            .unwrap_or_else(default_scope);
        let imports = take_string_array(&mut properties, "imports").map_err(ctx)?;
        let interceptors = take_string_array(&mut properties, "interceptors").map_err(ctx)?;
        let config = take_object(&mut properties, "config").map_err(ctx)?;
        let labels = take_string_map(&mut properties, "labels").map_err(ctx)?;

        if !properties.is_empty() {
            let unknown: Vec<_> = properties.keys().collect();
            return Err(anyhow::anyhow!(
                "Component '{name}' has unknown properties: {unknown:?}"
            ));
        }

        Ok(vec![Definition::Component(ComponentDefinition {
            name,
            uri,
            scope,
            imports,
            interceptors,
            config,
            labels,
        })])
    }
}

/// Handles `[capability.*]` definitions.
pub struct CapabilityConfigHandler;

impl ConfigHandler for CapabilityConfigHandler {
    fn claimed_categories(&self) -> Vec<CategoryClaim> {
        vec![CategoryClaim::all("capability")]
    }

    fn claimed_properties(&self) -> HashMap<&str, &[&str]> {
        HashMap::from([("capability", ["type", "scope"].as_slice())])
    }

    fn accepts_unclaimed_properties(&self, category: &str) -> bool {
        // Capability config blocks carry arbitrary type-specific keys
        // (forwarded to the registered capability implementation as
        // direct configuration).
        category == "capability"
    }

    fn handle_definition(&mut self, definition: GenericDefinition) -> Result<Vec<Definition>> {
        let GenericDefinition {
            category,
            name,
            mut properties,
        } = definition;
        if category != "capability" {
            return Err(anyhow::anyhow!(
                "CapabilityConfigHandler received unexpected category '{category}'"
            ));
        }
        let ctx = |e: PropertyError| e.with_context("capability", &name);
        let kind = take_required_string(&mut properties, "type").map_err(ctx)?;
        let scope = take_optional_string(&mut properties, "scope")
            .map_err(ctx)?
            .unwrap_or_else(default_scope);

        // Remaining properties are the capability's direct configuration
        let remaining: HashMap<String, serde_json::Value> = properties.into_iter().collect();

        Ok(vec![Definition::Capability(CapabilityDefinition {
            name,
            kind,
            scope,
            properties: remaining,
        })])
    }
}

/// Generates a `composable:runtime/function` for a target's function.
const FUNCTION_FACTORY: &str = "oci://ghcr.io/modulewise/component/function-factory:0.5.1";

/// Maps between JSON and the WIT values of generated functions.
const JSON_MAPPER: &str = "oci://ghcr.io/modulewise/component/json-mapper:0.4.0";

/// The mapper every generated function imports, emitted once.
const JSON_MAPPER_NAME: &str = "_json-mapper";

/// The function-factory options a `[function]` passes through.
const FUNCTION_OPTIONS: [&str; 3] = ["function", "world", "description"];

/// Handles `[function.*]` definitions.
///
/// A function is a component named `NAME`, generated by a function-factory
/// over its `target`, that exports `composable:runtime/function`.
#[derive(Default)]
pub struct FunctionConfigHandler {
    json_mapper_emitted: bool,
}

impl ConfigHandler for FunctionConfigHandler {
    fn claimed_categories(&self) -> Vec<CategoryClaim> {
        vec![CategoryClaim::all("function")]
    }

    fn claimed_properties(&self) -> HashMap<&str, &[&str]> {
        HashMap::from([(
            "function",
            ["target", "function", "world", "description", "labels"].as_slice(),
        )])
    }

    fn handle_definition(&mut self, definition: GenericDefinition) -> Result<Vec<Definition>> {
        let GenericDefinition {
            category,
            name,
            mut properties,
        } = definition;
        if category != "function" {
            return Err(anyhow::anyhow!(
                "FunctionConfigHandler received unexpected category '{category}'"
            ));
        }
        let ctx = |e: PropertyError| e.with_context("function", &name);
        let target = take_required_string(&mut properties, "target").map_err(ctx)?;
        let labels = take_string_map(&mut properties, "labels").map_err(ctx)?;
        let mut factory_config = HashMap::from([(
            "wit".to_string(),
            serde_json::Value::String(format!("${{wit({target})}}")),
        )]);
        for option in FUNCTION_OPTIONS {
            if let Some(value) = take_optional_string(&mut properties, option).map_err(ctx)? {
                factory_config.insert(option.to_string(), serde_json::Value::String(value));
            }
        }

        if !properties.is_empty() {
            let unknown: Vec<_> = properties.keys().collect();
            return Err(anyhow::anyhow!(
                "Function '{name}' has unknown properties: {unknown:?}"
            ));
        }

        // Internal, so `_` unless the function's own name is already internal.
        let factory = if name.starts_with('_') {
            format!("{name}-factory")
        } else {
            format!("_{name}-factory")
        };
        let mut definitions = vec![
            Definition::Component(ComponentDefinition {
                name,
                uri: format!("factory:{factory}"),
                scope: default_scope(),
                imports: vec![target, JSON_MAPPER_NAME.to_string()],
                interceptors: Vec::new(),
                config: HashMap::new(),
                labels,
            }),
            Definition::Component(ComponentDefinition {
                name: factory,
                uri: FUNCTION_FACTORY.to_string(),
                scope: default_scope(),
                imports: Vec::new(),
                interceptors: Vec::new(),
                config: factory_config,
                labels: HashMap::new(),
            }),
        ];
        if !self.json_mapper_emitted {
            self.json_mapper_emitted = true;
            definitions.push(Definition::Component(ComponentDefinition {
                name: JSON_MAPPER_NAME.to_string(),
                uri: JSON_MAPPER.to_string(),
                scope: default_scope(),
                imports: Vec::new(),
                interceptors: Vec::new(),
                config: HashMap::new(),
                labels: HashMap::new(),
            }));
        }
        Ok(definitions)
    }
}

// --- Property extractors ---

enum PropertyError {
    Missing {
        key: String,
    },
    TypeMismatch {
        key: String,
        expected: &'static str,
        got: serde_json::Value,
    },
}

impl PropertyError {
    fn with_context(self, category: &str, name: &str) -> anyhow::Error {
        match self {
            PropertyError::Missing { key } => {
                anyhow::anyhow!("{category} '{name}' missing required '{key}' field")
            }
            PropertyError::TypeMismatch { key, expected, got } => {
                anyhow::anyhow!("{category} '{name}': '{key}' must be {expected}, got {got}")
            }
        }
    }
}

fn take_required_string(properties: &mut PropertyMap, key: &str) -> Result<String, PropertyError> {
    match properties.remove(key) {
        Some(serde_json::Value::String(s)) => Ok(s),
        Some(got) => Err(PropertyError::TypeMismatch {
            key: key.into(),
            expected: "a string",
            got,
        }),
        None => Err(PropertyError::Missing { key: key.into() }),
    }
}

fn take_optional_string(
    properties: &mut PropertyMap,
    key: &str,
) -> Result<Option<String>, PropertyError> {
    match properties.remove(key) {
        Some(serde_json::Value::String(s)) => Ok(Some(s)),
        Some(got) => Err(PropertyError::TypeMismatch {
            key: key.into(),
            expected: "a string",
            got,
        }),
        None => Ok(None),
    }
}

fn take_string_array(
    properties: &mut PropertyMap,
    key: &str,
) -> Result<Vec<String>, PropertyError> {
    match properties.remove(key) {
        Some(serde_json::Value::Array(arr)) => {
            let mut result = Vec::with_capacity(arr.len());
            for item in arr {
                match item {
                    serde_json::Value::String(s) => result.push(s),
                    got => {
                        return Err(PropertyError::TypeMismatch {
                            key: key.into(),
                            expected: "an array of strings",
                            got,
                        });
                    }
                }
            }
            Ok(result)
        }
        Some(got) => Err(PropertyError::TypeMismatch {
            key: key.into(),
            expected: "an array",
            got,
        }),
        None => Ok(Vec::new()),
    }
}

fn take_object(
    properties: &mut PropertyMap,
    key: &str,
) -> Result<HashMap<String, serde_json::Value>, PropertyError> {
    match properties.remove(key) {
        Some(serde_json::Value::Object(map)) => Ok(map.into_iter().collect()),
        Some(got) => Err(PropertyError::TypeMismatch {
            key: key.into(),
            expected: "an object/table",
            got,
        }),
        None => Ok(HashMap::new()),
    }
}

fn take_string_map(
    properties: &mut PropertyMap,
    key: &str,
) -> Result<HashMap<String, String>, PropertyError> {
    match properties.remove(key) {
        Some(serde_json::Value::Object(map)) => {
            let mut result = HashMap::new();
            for (k, v) in map {
                let s = match v {
                    serde_json::Value::String(s) => s,
                    serde_json::Value::Number(n) => n.to_string(),
                    serde_json::Value::Bool(b) => b.to_string(),
                    got => {
                        return Err(PropertyError::TypeMismatch {
                            key: format!("{key}.{k}"),
                            expected: "a scalar value",
                            got,
                        });
                    }
                };
                result.insert(k, s);
            }
            Ok(result)
        }
        Some(got) => Err(PropertyError::TypeMismatch {
            key: key.into(),
            expected: "an object/table of strings",
            got,
        }),
        None => Ok(HashMap::new()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn function(name: &str, properties: serde_json::Value) -> GenericDefinition {
        let serde_json::Value::Object(properties) = properties else {
            panic!("properties must be an object");
        };
        GenericDefinition {
            category: "function".to_string(),
            name: name.to_string(),
            properties: properties.into_iter().collect(),
        }
    }

    fn components(definitions: Vec<Definition>) -> HashMap<String, ComponentDefinition> {
        definitions
            .into_iter()
            .map(|definition| match definition {
                Definition::Component(component) => (component.name.clone(), component),
                other => panic!("expected a component, got {other:?}"),
            })
            .collect()
    }

    #[test]
    fn a_function_emits_the_function_its_factory_and_the_mapper() {
        let mut handler = FunctionConfigHandler::default();
        let emitted = components(
            handler
                .handle_definition(function("greet", json!({ "target": "hello" })))
                .unwrap(),
        );
        assert_eq!(emitted.len(), 3);

        let greet = &emitted["greet"];
        assert_eq!(greet.uri, "factory:_greet-factory");
        assert_eq!(greet.imports, ["hello", "_json-mapper"]);
        assert!(greet.config.is_empty());

        let factory = &emitted["_greet-factory"];
        assert_eq!(factory.uri, FUNCTION_FACTORY);
        assert_eq!(
            factory.config,
            HashMap::from([("wit".to_string(), json!("${wit(hello)}"))])
        );

        assert_eq!(emitted["_json-mapper"].uri, JSON_MAPPER);
    }

    #[test]
    fn the_mapper_is_emitted_once() {
        let mut handler = FunctionConfigHandler::default();
        let first = components(
            handler
                .handle_definition(function("greet1", json!({ "target": "hello" })))
                .unwrap(),
        );
        let second = components(
            handler
                .handle_definition(function("greet2", json!({ "target": "hello" })))
                .unwrap(),
        );
        assert!(first.contains_key("_json-mapper"));
        assert!(!second.contains_key("_json-mapper"));
        assert_eq!(second["greet2"].imports, ["hello", "_json-mapper"]);
    }

    #[test]
    fn options_go_to_the_factory_and_labels_to_the_function() {
        let mut handler = FunctionConfigHandler::default();
        let emitted = components(
            handler
                .handle_definition(function(
                    "greet",
                    json!({
                        "target": "hello",
                        "function": "greeter.greet",
                        "world": "greeter",
                        "description": "Greet someone by name",
                        "labels": { "domain": "greetings" },
                    }),
                ))
                .unwrap(),
        );
        assert_eq!(
            emitted["_greet-factory"].config,
            HashMap::from([
                ("wit".to_string(), json!("${wit(hello)}")),
                ("function".to_string(), json!("greeter.greet")),
                ("world".to_string(), json!("greeter")),
                ("description".to_string(), json!("Greet someone by name")),
            ])
        );
        assert_eq!(
            emitted["greet"].labels,
            HashMap::from([("domain".to_string(), "greetings".to_string())])
        );
        assert!(emitted["_greet-factory"].labels.is_empty());
    }

    #[test]
    fn an_internal_function_gets_no_second_underscore() {
        let mut handler = FunctionConfigHandler::default();
        let emitted = components(
            handler
                .handle_definition(function(
                    "_forecast-function",
                    json!({ "target": "weather" }),
                ))
                .unwrap(),
        );
        assert_eq!(
            emitted["_forecast-function"].uri,
            "factory:_forecast-function-factory"
        );
        assert!(emitted.contains_key("_forecast-function-factory"));
    }

    #[test]
    fn a_missing_target_fails() {
        let error = FunctionConfigHandler::default()
            .handle_definition(function("greet", json!({})))
            .unwrap_err()
            .to_string();
        assert_eq!(error, "function 'greet' missing required 'target' field");
    }

    #[test]
    fn a_non_string_option_fails() {
        let error = FunctionConfigHandler::default()
            .handle_definition(function("greet", json!({ "target": "hello", "world": 1 })))
            .unwrap_err()
            .to_string();
        assert_eq!(error, "function 'greet': 'world' must be a string, got 1");
    }
}
